function humanize(name: string): string {
  return name.replaceAll(".", " ").replaceAll("_", " ");
}

const resourceTemplates: Record<string, string> = {
  project: "project",
  asset: "assets/{targetId}",
  sequence: "sequences/{sequenceId}",
  track: "sequences/{sequenceId}/tracks/{trackId}",
  editorial: "sequences/{sequenceId}/tracks/{trackId}/items",
  transform:
    "sequences/{sequenceId}/tracks/{trackId}/items/{targetId}/transform",
  transition: "sequences/{sequenceId}/tracks/{trackId}/items/{targetId}",
  effects: "effects/{effectId}",
  color: "effects/color/{targetId}",
  audio: "audio/{targetId}",
  captions: "sequences/{sequenceId}/captions",
  markers: "sequences/{sequenceId}/markers",
  analysis: "analyses/{targetId}",
  semantic: "project/derived-semantic-state",
  render: "jobs/{jobId}",
  interchange: "project/interchange",
};

function conflictSets(
  family: string,
  name: string,
): Pick<OperationDescriptor, "readSet" | "writeSet" | "expectedWarnings"> {
  const resource = resourceTemplates[family] ?? "project";
  const readOnly =
    name.endsWith(".detect") ||
    name.endsWith(".search") ||
    name.startsWith("preview.") ||
    name === "render.start" ||
    name.startsWith("semantic.find_");
  const destructive =
    name.includes("remove") ||
    name.includes("delete") ||
    name.includes("extract") ||
    name.includes("overwrite") ||
    name.includes("flatten");
  return {
    readSet: ["project.revision", resource],
    writeSet: readOnly ? [] : [resource],
    expectedWarnings: destructive
      ? ["Operation may remove or replace existing timeline state"]
      : [],
  };
}

export const operationCatalog: OperationDescriptor[] = Object.entries(
  operationFamilies,
).flatMap(([family, names]) =>
  names.map((name) => ({
    name,
    family,
    description: `FrameOS operation: ${humanize(name)}.`,
    maturity: implementedOperations.has(name)
      ? "implemented"
      : implementedServiceOperations.has(name)
        ? "service"
        : "contract",
    reversible: !name.endsWith(".detect") && !name.startsWith("render."),
    requiredCapabilities:
      name === "asset.proxy.create"
        ? ["asset.proxy.create"]
        : name === "asset.thumbnail.create"
          ? ["asset.thumbnail.create"]
          : name === "preview.waveform"
            ? ["preview.waveform"]
            : name.startsWith("render.") || name.startsWith("preview.")
              ? ["engine.mlt"]
              : [],
    ...conflictSets(family, name),
  })),
);

export function findOperation(name: string): OperationDescriptor | undefined {
  return operationCatalog.find((operation) => operation.name === name);
}
