import { z } from "zod";

export const capabilityKinds = [
  "producer",
  "consumer",
  "filter",
  "transition",
  "analyzer",
  "codec",
  "hardware",
  "interchange",
  "operation",
] as const;

export const capabilityDescriptorSchema = z
  .object({
    id: z.string().min(1).max(512),
    kind: z.enum(capabilityKinds),
    name: z.string().min(1).max(512),
    description: z.string().max(8_192),
    available: z.boolean(),
    baseline: z.boolean(),
    provider: z.string().min(1).max(256),
    providerVersion: z.string().max(128).optional(),
    license: z.string().max(128).optional(),
    reasonUnavailable: z.string().max(4_096).optional(),
    alternatives: z.array(z.string().max(512)),
    parameters: z.record(z.string(), z.unknown()).optional(),
    metadata: z.record(z.string(), z.unknown()),
  })
  .strict();

export type CapabilityDescriptor = z.infer<typeof capabilityDescriptorSchema>;

